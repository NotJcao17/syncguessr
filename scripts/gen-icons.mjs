// Generates src/components/Icon.tsx from the Solar "broken" set (same family Syncora Player uses).
// Run: node scripts/gen-icons.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = require("@iconify-json/solar/icons.json");

const ICONS = {
  play: "play",
  pause: "pause",
  search: "magnifier",
  close: "close-circle",
  filters: "tuning-2",
  help: "question-circle",
  refresh: "refresh",
  skip: "skip-next",
  volume: "volume-loud",
  volumeLow: "volume-small",
  mute: "volume-cross",
  note: "music-note",
  notes: "music-notes",
  trophy: "cup-star",
  crown: "crown-minimalistic",
  chart: "chart-2",
  calendar: "calendar-date",
  share: "share",
  link: "link-round",
  copy: "copy",
  mic: "microphone-3",
  check: "check-circle",
  danger: "danger-circle",
  back: "alt-arrow-left",
  next: "arrow-right",
  down: "alt-arrow-down",
  stopwatch: "stopwatch",
  shuffle: "shuffle",
  users: "users-group-two-rounded",
  keyboard: "keyboard",
  flag: "flag",
  fire: "fire",
  history: "history",
  trash: "trash-bin-trash",
  add: "add-circle",
  home: "home-2",
  restart: "restart",
  vinyl: "vinyl",
  info: "info-circle",
  soundwave: "soundwave",
  star: "star",
};

const entries = Object.entries(ICONS).map(([name, id]) => {
  const icon = set.icons[`${id}-broken`];
  if (!icon) throw new Error(`Missing solar icon ${id}-broken`);
  return `  ${name}: ${JSON.stringify(icon.body)},`;
});

const file = `// Generated by scripts/gen-icons.mjs from @iconify-json/solar (broken style). Do not edit.
import type { SVGProps } from "react";

const BODIES = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof BODIES;

export function Icon({ name, className = "size-5", ...rest }: { name: IconName } & SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="0 0 24 24"
      className={className}
      aria-hidden="true"
      focusable="false"
      {...rest}
      dangerouslySetInnerHTML={{ __html: BODIES[name] }}
    />
  );
}
`;
writeFileSync("src/components/Icon.tsx", file);
console.log(`wrote ${entries.length} icons`);
